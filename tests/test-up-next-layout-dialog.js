'use strict';
var assert = require('assert');
var Dialog = require('../app/up-next-layout-dialog');
var dialog = Dialog.create();
dialog.open('bottom-panel');
assert.strictEqual(dialog.snapshot().focus, 1, 'opens on the saved layout');
dialog.moveHorizontal(-1);
assert.strictEqual(dialog.snapshot().focus, 1, 'horizontal input does not move between layout previews');
dialog.moveVertical(-1);
assert.strictEqual(dialog.snapshot().focus, 0, 'moves up between layout previews');
dialog.moveVertical(1);
assert.strictEqual(dialog.snapshot().focus, 1, 'moves down to the second layout preview');
dialog.moveVertical(1);
assert.strictEqual(dialog.snapshot().focus, 2, 'moves down from the previews to Cancel');
dialog.moveHorizontal(1);
assert.strictEqual(dialog.snapshot().focus, 3, 'moves right from Cancel to Apply');
dialog.choose('compact');
assert.strictEqual(dialog.snapshot().focus, 3, 'choosing a layout moves directly to Apply');
dialog.choose('compact');
assert.strictEqual(dialog.confirm(), 'compact', 'confirms the selected layout');
dialog.close();
assert.strictEqual(dialog.snapshot().open, false, 'closes cleanly');
console.log('Up Next layout dialog checks passed');
